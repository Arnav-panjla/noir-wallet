static const uint8_t* SSD1306_GetGlyph(char c) {
    static const uint8_t blank[5] = {0x00,0x00,0x00,0x00,0x00};
    if (c < 0x20 || c > 0x7E) return blank;
    return FONT5X7[(unsigned char)c - 0x20];
}

void SSD1306_DrawChar(int16_t x, int16_t y, char c, uint8_t scale) {
    const uint8_t *glyph = SSD1306_GetGlyph(c);
    for (int8_t col = 0; col < 5; col++) {
        uint8_t line = glyph[col];
        for (int8_t row = 0; row < 7; row++) {
            if (line & (1 << row)) {
                for (uint8_t sx = 0; sx < scale; sx++) {
                    for (uint8_t sy = 0; sy < scale; sy++) {
                        SSD1306_DrawPixel(x + col * scale + sx, y + row * scale + sy, 1);
                    }
                }
            }
        }
    }
}

void SSD1306_DrawString(int16_t x, int16_t y, const char *str, uint8_t scale) {
    int16_t cursor = x;
    while (*str) {
        SSD1306_DrawChar(cursor, y, *str, scale);
        cursor += 6 * scale; // 5px glyph + 1px spacing
        str++;
    }
}