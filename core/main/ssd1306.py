    def _init_display(self):
        cmds = [
            0xAE, 0xD5, 0x80, 0xA8, 0x3F, 0xD3, 0x00, 0x40,
            0x8D, 0x14, 0x20, 0x00, 0xA1, 0xC8, 0xDA, 0x12,
            0x81, 0xCF, 0xD9, 0xF1, 0xDB, 0x40, 0xA4, 0xA6, 0xAF
        ]
        self._write_cmd(cmds)
        time.sleep(0.1)

    def _write_cmd(self, cmd):
        if isinstance(cmd, list):
            data = bytearray([0x00] + cmd)
        else:
            data = bytearray([0x00, cmd])
        self.i2c.writeto(self.addr, data)

    def _write_data(self, data):
        self.i2c.writeto(self.addr, bytearray([0x40]) + data)

    def show(self):
        for page in range(self.pages):
            self._write_cmd([0xB0 + page, 0x00, 0x10])
            self._write_data(self.buffer[page * self.width:(page + 1) * self.width])

    def fill(self, color):
        self.buffer[:] = (0xFF if color else 0x00) * len(self.buffer)

    def pixel(self, x, y, color):
        if x < 0 or x >= self.width or y < 0 or y >= self.height:
            return
        index = (y // 8) * self.width + x
        bit = y % 8
        if color:
            self.buffer[index] |= (1 << bit)
        else:
            self.buffer[index] &= ~(1 << bit)

    def text(self, text, x, y, color=1):
        for i, char in enumerate(text):
            if char in self._font:
                cols = self._font[char]
                for col_idx, col_val in enumerate(cols):
                    for row in range(8):
                        if col_val & (1 << row):
                            self.pixel(x + i * 6 + col_idx, y + row, color)

    def hline(self, x, y, w, color):
        for i in range(w):
            self.pixel(x + i, y, color)

    def vline(self, x, y, h, color):
        for i in range(h):
            self.pixel(x, y + i, color)

    def rect(self, x, y, w, h, color):
        self.hline(x, y, w, color)
        self.hline(x, y + h - 1, w, color)
        self.vline(x, y, h, color)
        self.vline(x + w - 1, y, h, color)

    def clear(self):
        self.fill(0)

    def poweron(self):
        self._write_cmd(0xAF)

    def poweroff(self):
        self._write_cmd(0xAE)

    def contrast(self, value):
        self._write_cmd([0x81, value])

    def invert(self, value):
        self._write_cmd(0xA7 if value else 0xA6)
